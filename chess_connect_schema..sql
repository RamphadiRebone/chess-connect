  CREATE OR REPLACE FORCE EDITIONABLE VIEW "MATCH_PLAYER_DETAILS" ("Match Id", "White Player Name", "Black Player Name", "Match Date", "Match Result") AS 
  SELECT 
    M.MATCH_ID AS "Match Id",
    NVL(P1.FIRST_NAME || ' ' || P1.LAST_NAME, 'Player ID: ' || M.WHITE_PLAYER_ID) AS "White Player Name",
    NVL(P2.FIRST_NAME || ' ' || P2.LAST_NAME, 'Player ID: ' || M.BLACK_PLAYER_ID) AS "Black Player Name",
    M.MATCH_DATE AS "Match Date",
    M.RESULT AS "Match Result"
FROM MATCHES M
LEFT JOIN PLAYERS PL1 ON M.WHITE_PLAYER_ID = PL1.PLAYER_ID
LEFT JOIN PERSONS P1  ON PL1.PERSON_ID = P1.PERSON_ID
LEFT JOIN PLAYERS PL2 ON M.BLACK_PLAYER_ID = PL2.PLAYER_ID
LEFT JOIN PERSONS P2  ON PL2.PERSON_ID = P2.PERSON_ID;

