  CREATE OR REPLACE FORCE EDITIONABLE VIEW "PLAYER_STANDINGS" ("RANK", "PLAYER_ID", "FULLNAME", "MATCHES_PLAYED", "WINS", "DRAWS", "LOSSES", "TOTAL_POINTS") AS 
  SELECT 
    DENSE_RANK() OVER (ORDER BY SUM(pmp.points) DESC, SUM(pmp.win) DESC) AS RANK,
    pmp.player_id AS PLAYER_ID,
    p.first_name || ' ' || p.last_name AS FULLNAME,
    COUNT(*) AS MATCHES_PLAYED,
    SUM(pmp.win) AS WINS,
    SUM(pmp.draw) AS DRAWS,
    SUM(pmp.loss) AS LOSSES,
    SUM(pmp.points) AS TOTAL_POINTS
FROM 
    (
        SELECT white_player_id AS player_id,
               CASE WHEN result = '1-0' THEN 1.0 WHEN result = '0.5-0.5' THEN 0.5 ELSE 0.0 END AS points,
               CASE WHEN result = '1-0' THEN 1 ELSE 0 END AS win,
               CASE WHEN result = '0.5-0.5' THEN 1 ELSE 0 END AS draw,
               CASE WHEN result = '0-1' THEN 1 ELSE 0 END AS loss
          FROM matches
         WHERE result IS NOT NULL
        UNION ALL
        SELECT black_player_id AS player_id,
               CASE WHEN result = '0-1' THEN 1.0 WHEN result = '0.5-0.5' THEN 0.5 ELSE 0.0 END AS points,
               CASE WHEN result = '0-1' THEN 1 ELSE 0 END AS win,
               CASE WHEN result = '0.5-0.5' THEN 1 ELSE 0 END AS draw,
               CASE WHEN result = '1-0' THEN 1 ELSE 0 END AS loss
          FROM matches
         WHERE result IS NOT NULL
    ) pmp,
    players pl,
    persons p
WHERE 
    pl.player_id = pmp.player_id
    AND p.person_id = pl.person_id
GROUP BY 
    pmp.player_id, p.first_name, p.last_name;